import os
import httpx
from dotenv import load_dotenv

load_dotenv()

BOT_TOKEN = os.getenv("CONTENT_FACTORY_BOT")
CHAT_ID = os.getenv("TG_CHAT_ID_MAIN")

strategy = """🚀 **B2B Outreach Strategy (Alex Hormozi Framework)** 🚀

Твоя главная метрика — **записи на CustDev (звонки)**. 
Цель первого сообщения — НЕ продать услугу, а продать **СЛЕДУЮЩИЙ ШАГ** (звонок или согласие на отправку войса/материалов).

Формула оффера: *(Dream Outcome × Likelihood of Achievement) / (Time Delay × Effort)*

### 🔢 Этапы Аутрича (Каденция)

**День 1: Отправка "Киллер Оффера" (WhatsApp / TG)**
- *Хук (повод написать):* "Привет, {Имя}! Вижу, вы сейчас активно растете / выиграли тендер / ищете маркетолога."
- *Dream Outcome + Likelihood:* "Мы внедрили ИИ-ассистента в 3-х компаниях из вашей ниши — это сократило цикл сделки вдвое и увеличило конверсию на 40%."
- *Time Delay + Effort:* "Всё под ключ за 14 дней. Вашей команде не нужно переучиваться."
- *CTA (Мягкий):* "У меня есть 2-минутный кейс о том, как мы это сделали. Могу скинуть войс/видео?" *(Никаких ссылок в первом сообщении!)*

**День 2: Фокус на Боль (Если игнор)**
- "Привет! Возможно, сообщение затерялось. Кстати, заметил, что у вас [указать конкретную проблему, например: отдел продаж долго отвечает на заявки ночью]. Вы сейчас решаете эту задачу или пока не в приоритете?"

**День 5: Доказательство (Social Proof / Value)**
- "Слушай, {Имя}, не хочу спамить. Просто мы тут на днях упаковали бота для [Имя конкурента/Смежная ниша], и он за выходные закрыл 5 сделок без участия менеджеров. Если актуально обсудить — дай знать, запишемся на 15 мин зум."

**День 14: Breakup Message (Прощание)**
- "Привет, {Имя}. Вижу, сейчас ИИ-автоматизация не в фокусе. Закрываю эту задачу у себя. Если когда-нибудь решите ускорить отдел продаж — буду на связи. Хорошей недели!"
*(Психология: люди ненавидят, когда у них что-то отнимают. Часто отвечают именно на это сообщение).*

---
🔥 **Золотые правила:**
1. Никаких ссылок в первом сообщении (повышает доверие и защищает от бана).
2. Максимум 3-5 предложений. Люди не читают лонгриды.
3. Разговаривай "в мире клиента": не продавай ботов, продавай сэкономленные деньги и время.
"""

url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
payload = {
    "chat_id": CHAT_ID,
    "text": strategy,
    "parse_mode": "Markdown"
}

resp = httpx.post(url, json=payload)
print(f"Status: {resp.status_code}, Response: {resp.text}")
