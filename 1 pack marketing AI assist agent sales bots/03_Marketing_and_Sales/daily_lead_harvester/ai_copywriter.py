import os
import requests
import json
import logging

logger = logging.getLogger(__name__)

def generate_lead_draft_and_offer(lead):
    """
    Генерация персонализированного 1-го сообщения и оффера для конкретного лида.
    Использует умный сопоставитель на основе направления (ИИ, маркетинг, боты, контекст, контент).
    При наличии API ключа может задействовать LLM.
    """
    company = lead.get("company", "Коллеги")
    query = lead.get("query", "").lower()
    source = lead.get("source", "")
    details = lead.get("details", "")
    contact_person = lead.get("contact_person", "")

    greeting = f"Здравствуйте, {contact_person}!" if contact_person and contact_person != "Не указано" and contact_person != "Руководитель компании" else f"Здравствуйте, команда {company}!"

    # Определяем категорию запроса
    if "ии" in query or "нейро" in query or "ai" in query:
        niche = "ИИ и Автоматизация"
        draft = (
            f"{greeting}\n"
            f"Увидели ваш запрос/вакансию по направлению ИИ и нейросетям.\n"
            f"Мы внедряем автономных ИИ-агентов и скрипты автоматизации, которые сокращают рутину команды до 70% и окупаются за первый месяц.\n"
            f"Подскажите, актуальна ли для вас сейчас задача по внедрению ИИ решений?"
        )
        offer = (
            "🎯 Что можем предложить:\n"
            "1. Разработка автономных ИИ-агентов (отвечают клиентам, парсят данные, обрабатывают документы).\n"
            "2. Интеграция LLM (Gemini/ChatGPT/Claude) в ваши текущие бизнес-процессы или CRM.\n"
            "3. Экспресс-аудит бизнес-процессов: где ИИ сэкономит от 500k ₸ / $1000 в месяц."
        )

    elif "бот" in query:
        niche = "Чат-боты и Автоматизация"
        draft = (
            f"{greeting}\n"
            f"Заметили ваш запрос по разработке чат-ботов.\n"
            f"Создаем умных ботов для Telegram и WhatsApp с интеграцией AI, CRM, оплаты и сквозной аналитики.\n"
            f"Подскажите, под какую именно задачу вы ищете бота (продажи, поддержка, лидогенерация)?"
        )
        offer = (
            "🎯 Что можем предложить:\n"
            "1. Умный отдел продаж в Telegram/WhatsApp с ИИ-менеджером, дожимающим лиды 24/7.\n"
            "2. Парсеры и квалификаторы лидов с автоматической передачей контактов в CRM.\n"
            "3. Бот-каталог/сервис с быстрой онлайн-оплатой и приемом заказов."
        )

    elif "маркетинг" in query or "smm" in query:
        niche = "Маркетинг и Лидогенерация"
        draft = (
            f"{greeting}\n"
            f"Обратили внимание на ваш интерес к развитию маркетинга и сбору лидов.\n"
            f"Строим сквозные системы лидогенерации (автоворонки + AI контент + таргетинг) с гарантией стоимости целевой заявки.\n"
            f"Будет ли вам интересно взглянуть на кейс по привлечению 150+ целевых B2B лидов за 2 недели?"
        )
        offer = (
            "🎯 Что можем предложить:\n"
            "1. Построение автоворонки лидогенерации (Telegram/WhatsApp/Socials).\n"
            "2. Комплексный B2B аутрич и парсинг целевой аудитории с готовыми питчами.\n"
            "3. Упаковка позиционирования и контент-стратегия с высоким ROI."
        )

    elif "контекст" in query or "директ" in query or "ppc" in query or "google" in query:
        niche = "Контекстная реклама (PPC)"
        draft = (
            f"{greeting}\n"
            f"Нашли вашу вакансию/проект по настройке контекстной рекламы.\n"
            f"Специализируемся на Яндекс.Директ и Google Ads для коммерческих ниш с глубокой аналитикой сквозной конверсии.\n"
            f"Готовы провести бесплатный аудит ваших текущих кампаний и показать, где сливается до 30% бюджета. Интересно проверить?"
        )
        offer = (
            "🎯 Что можем предложить:\n"
            "1. Экспресс-аудит текущих рекламных кампаний в Яндекс.Директ / Google Ads.\n"
            "2. Настройка контекстной рекламы под ключ с установкой пикселей и систем аналитики.\n"
            "3. Оптимизация стоимости клика (CPC) и конверсии в заявку (CPL)."
        )

    elif "контент" in query:
        niche = "ИИ Контент и Медиа"
        draft = (
            f"{greeting}\n"
            f"Увидели ваш запрос по созданию ИИ-контента.\n"
            f"Автоматизируем производство вирусных роликов (Reels/Shorts/TikTok), статей и графики с помощью нейросетей, сокращая затраты на продакшн в 5 раз.\n"
            f"Вы ищете решение под соцсети компании или под регулярный контент-план?"
        )
        offer = (
            "🎯 Что можем предложить:\n"
            "1. Генерация вирусного медиаконтента (нейро-аватары, озвучка, сценарии).\n"
            "2. Автоматическая система массового монтажа и загрузки видео на YouTube/Drive.\n"
            "3. Запуск контент-завода для ежедневной публикации без ручного труда."
        )

    else:
        niche = "Веб-разработка и Софт"
        draft = (
            f"{greeting}\n"
            f"Заметили вашу задачу по направлению [{query}].\n"
            f"Наша команда разрабатывает высоконагруженные веб-системы, сервисы и боты под ключ с гарантийной поддержкой.\n"
            f"Удобно ли обсудить детали вашей задачи в коротком созвоне или переписке?"
        )
        offer = (
            "🎯 Что можем предложить:\n"
            "1. Кастомная разработка веб-сервиса / мобильного приложения / CRM.\n"
            "2. Интеграции сторонних API, платежных систем и автоматизаций n8n/Python.\n"
            "3. Техническое сопровождение и доработка существующего кода."
        )

    return {
        "niche": niche,
        "draft_message": draft,
        "offer_proposal": offer
    }
